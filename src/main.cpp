//******************************************************************************
//         file name:  j4_stepper.ino
//      v0_1 created:  2026-06-14 -- 0123 CDT -KL
//      last updated:  2026-06-14 -- 0123 CDT -KL
//            author:  Kevin Lange
//       description:  Dedicated stepper driver board for Johnny 4, running on
//                     an ESP32-DEV (WROOM) module. Listens for ASCII position
//                     packets from j4_receiver (TTGO) over UART1 and drives
//                     five stepper motors:
//                       3x BTT TMC5160T  -- neck left, neck right, neck pivot
//                       2x TMC2209       -- eye-pop left + right (ganged, one
//                                           step/dir pair drives both)
//
//                     Step pulses are generated by the ESP32 RMT peripheral via
//                     FastAccelStepper (no CPU blocking). The TMC5160T drivers
//                     are configured once over software SPI; the TMC2209 pair
//                     is configured once over a shared single-wire UART bus.
//                     Library and motion settings are copied from j4_receiver /
//                     j4_motor_test_dev so the neck moves exactly as before.
//       update log:  v0_1 -- Initial build. Fixed-buffer ASCII parser, 5 motors.
//
//
//
//  ------------------------------------------------------------------
//  INCOMING PACKET FORMAT (from j4_receiver over UART1)
//  ------------------------------------------------------------------
//   "nL,nR,nP,eye\n"   four comma-separated integers, newline terminated
//     nL  -- neck left   joystick value   (0-3200)
//     nR  -- neck right  joystick value   (0-3200)
//     nP  -- neck pivot  joystick value   (0-3200)
//     eye -- eye-pop     value            (0-255)
//   Any line that does not parse to exactly four ints is ignored, so a
//   half-received line on power-up cannot move a motor.
//  ------------------------------------------------------------------
//
//
//  ESP32-DEV (WROOM) Pin Connections
//  ------------------------------------------------------------------
//  TMC5160T software SPI (shared SCK/MOSI/MISO, one CS per driver):
//   18:  SPI SCK   -- all three TMC5160T (shared)
//   19:  SPI MISO  -- all three TMC5160T SDO (shared)
//   23:  SPI MOSI  -- all three TMC5160T SDI (shared)
//   05:  CS -- neck-left  TMC5160T
//   17:  CS -- neck-right TMC5160T
//   16:  CS -- neck-pivot TMC5160T
//
//  Neck step/dir:
//   26:  STEP -- neck left      25:  DIR -- neck left
//   33:  STEP -- neck right     32:  DIR -- neck right
//   27:  STEP -- neck pivot     14:  DIR -- neck pivot
//
//  Eye-pop (two TMC2209 wired in parallel -- one step/dir pair drives both):
//   13:  STEP -- both eye-pop drivers
//   04:  DIR  -- both eye-pop drivers
//   21:  UART2 TX -- TMC2209 PDN_UART (via 1k to each driver)
//   22:  UART2 RX -- TMC2209 PDN_UART
//        TMC2209 addresses set by MS1/MS2 straps: driver0 = 0b00, driver1 = 0b01
//
//  Link from j4_receiver (TTGO):
//   35:  UART1 RX  <-- TTGO UART1 TX   (one-way; input-only pin, fine for RX)
//
//  Power / enable:
//   3.3V -> all driver VIO       GND -> all driver GND (common with ESP32)
//   12-24V PSU -> all driver VM  (PSU GND common with ESP32 GND)
//   All driver EN pins tied to GND -- drivers always enabled.
//  ------------------------------------------------------------------
//
//  NOTE: avoids strapping pins (0/2/12/15) for outputs and flash pins (6-11).
//        On WROVER modules GPIO 16/17 are used by PSRAM -- this build targets
//        a plain WROOM ESP32-DEV where 16/17 are free.
//
//******************************************************************************



#include <Arduino.h>
#include <SPI.h>
#include <HardwareSerial.h>
#include <TMCStepper.h>
#include "FastAccelStepper.h"


// ---------------------------------------------------------------------------
// PIN ASSIGNMENTS
// ---------------------------------------------------------------------------
// TMC5160T software SPI (shared bus, configured once in setup, idle while running)
#define SPI_SCK_PIN   18
#define SPI_MISO_PIN  19
#define SPI_MOSI_PIN  23
#define CS_PIN_NL      5   // neck left
#define CS_PIN_NR     17   // neck right
#define CS_PIN_NP     16   // neck pivot

// Neck step/dir
#define STEP_PIN_NL   26
#define DIR_PIN_NL    25
#define STEP_PIN_NR   33
#define DIR_PIN_NR    32
#define STEP_PIN_NP   27
#define DIR_PIN_NP    14

// Eye-pop: both TMC2209 drivers share ONE step pin and ONE dir pin so the two
// motors always move together at the same speed and direction.
#define STEP_PIN_EYE  13
#define DIR_PIN_EYE    4

// TMC2209 single-wire UART bus (both drivers share it, addressed via MS1/MS2)
#define TMC2209_TX    21
#define TMC2209_RX    22

// Link from the TTGO receiver (one-way: we only listen)
#define LINK_RX_PIN   35


// ---------------------------------------------------------------------------
// DRIVER + MOTION CONFIG  (matched to j4_receiver / j4_motor_test_dev)
// ---------------------------------------------------------------------------
// Neck -- BTT TMC5160T V1.0 + STEPPERONLINE 17HE24-2104S
#define R_SENSE_5160      0.075f  // BTT TMC5160T V1.0 sense resistor
#define NECK_CURRENT      2100    // RMS mA -- motor rated current
#define NECK_MICROSTEPS     16
#define NECK_SPEED_HZ     3200    // microsteps/sec (16x) ~ 60 RPM on a 1.8deg motor
#define NECK_ACCEL       16000    // microsteps/sec^2
#define NECK_THRESHOLD      20    // min joystick-unit change (0-3200) to re-issue moveTo

// Eye-pop -- TMC2209 (current/microstep settable over UART)
#define R_SENSE_2209      0.11f   // typical BTT/FYSETC TMC2209 sense resistor -- verify on your board
#define EYE_CURRENT        800    // RMS mA -- placeholder, tune to your eye-pop motors
#define EYE_MICROSTEPS      16
#define EYE_SPEED_HZ      3200    // tune for the eye-pop "feel"
#define EYE_ACCEL        16000
#define EYE_TRAVEL        1600    // microsteps of travel mapped from eye value 0..255
#define EYE_THRESHOLD        2    // min eye-unit change (0-255) to re-issue moveTo

// Defaults at boot (centre the neck, eyes retracted)
#define NECK_CENTER       1600    // joystick midpoint (0-3200)


// ---------------------------------------------------------------------------
// DRIVERS
// ---------------------------------------------------------------------------
// TMC5160T -- software SPI: TMC5160Stepper(CS, RS, MOSI, MISO, SCK)
TMC5160Stepper tmc_NL(CS_PIN_NL, R_SENSE_5160, SPI_MOSI_PIN, SPI_MISO_PIN, SPI_SCK_PIN);
TMC5160Stepper tmc_NR(CS_PIN_NR, R_SENSE_5160, SPI_MOSI_PIN, SPI_MISO_PIN, SPI_SCK_PIN);
TMC5160Stepper tmc_NP(CS_PIN_NP, R_SENSE_5160, SPI_MOSI_PIN, SPI_MISO_PIN, SPI_SCK_PIN);

// TMC2209 -- shared UART, addresses 0b00 and 0b01 set by MS1/MS2 straps
HardwareSerial tmcSerial(2);  // UART2 -> TMC2209 PDN_UART bus
TMC2209Stepper tmc_EYE0(&tmcSerial, R_SENSE_2209, 0b00);
TMC2209Stepper tmc_EYE1(&tmcSerial, R_SENSE_2209, 0b01);


// ---------------------------------------------------------------------------
// STEP GENERATORS (FastAccelStepper -- RMT hardware, no CPU blocking)
// ---------------------------------------------------------------------------
FastAccelStepperEngine engine;
FastAccelStepper *stepper_NL  = NULL;
FastAccelStepper *stepper_NR  = NULL;
FastAccelStepper *stepper_NP  = NULL;
FastAccelStepper *stepper_EYE = NULL;  // single generator drives both eye drivers

// Last commanded raw values (for the change threshold filter)
int last_nL  = NECK_CENTER;
int last_nR  = NECK_CENTER;
int last_nP  = NECK_CENTER;
int last_eye = 0;


// ---------------------------------------------------------------------------
// INCOMING LINK (UART1 from TTGO) + fixed-buffer parser (no String -> no heap churn)
// ---------------------------------------------------------------------------
HardwareSerial linkSerial(1);  // UART1
#define LINK_BAUD 250000       // matches stepperSerial baud in j4_receiver
char    rxBuf[48];
uint8_t rxLen = 0;


// Map the same way j4_receiver used to: neck travel is half a joystick range.
static inline int32_t neckTarget(int joy)      { return (int32_t)joy / 2; }
static inline int32_t neckTargetInv(int joy)   { return (int32_t)(3200 - joy) / 2; }
static inline int32_t eyeTarget(int eye)       { return (int32_t)map(eye, 0, 255, 0, EYE_TRAVEL); }


// Apply one parsed packet to the motors, with the per-axis change threshold so
// ADC noise at rest does not make the motors jitter.
void applyTargets(int nL, int nR, int nP, int eye) {
  if (stepper_NL && abs(nL - last_nL) >= NECK_THRESHOLD) {
    last_nL = nL;
    stepper_NL->moveTo(neckTargetInv(nL));   // neck-left ran inverted in j4_receiver
  }
  if (stepper_NR && abs(nR - last_nR) >= NECK_THRESHOLD) {
    last_nR = nR;
    stepper_NR->moveTo(neckTarget(nR));
  }
  if (stepper_NP && abs(nP - last_nP) >= NECK_THRESHOLD) {
    last_nP = nP;
    stepper_NP->moveTo(neckTarget(nP));
  }
  if (stepper_EYE && abs(eye - last_eye) >= EYE_THRESHOLD) {
    last_eye = eye;
    stepper_EYE->moveTo(eyeTarget(eye));
  }
}


// Parse "nL,nR,nP,eye". Only acts when all four fields are present.
void parseLine(const char *line) {
  int nL, nR, nP, eye;
  if (sscanf(line, "%d,%d,%d,%d", &nL, &nR, &nP, &eye) == 4) {
    applyTargets(nL, nR, nP, eye);
  }
}


// Configure one TMC5160T exactly as j4_receiver / j4_motor_test_dev does.
void configTmc5160(TMC5160Stepper &drv) {
  drv.begin();
  drv.GSTAT(0);          // clear latched fault flags
  drv.toff(4);           // chopper off time (0 disables the driver)
  drv.blank_time(24);
  drv.rms_current(NECK_CURRENT);
  drv.microsteps(NECK_MICROSTEPS);
  drv.en_pwm_mode(true); // StealthChop
  drv.pwm_autoscale(true);
}


// Configure one TMC2209 over the shared UART bus.
void configTmc2209(TMC2209Stepper &drv) {
  drv.begin();
  drv.toff(4);
  drv.blank_time(24);
  drv.rms_current(EYE_CURRENT);
  drv.microsteps(EYE_MICROSTEPS);
  drv.en_spreadCycle(false);  // StealthChop (quiet)
  drv.pwm_autoscale(true);
}


void setup() {
  Serial.begin(115200);
  delay(300);
  Serial.println("j4_stepper booting...");

  // --- Link from the TTGO (receive only) ---
  linkSerial.begin(LINK_BAUD, SERIAL_8N1, LINK_RX_PIN, -1);

  // --- TMC5160T neck drivers over software SPI ---
  configTmc5160(tmc_NL);
  configTmc5160(tmc_NR);
  configTmc5160(tmc_NP);
  Serial.print("NL GSTAT 0x");  Serial.print(tmc_NL.GSTAT(), HEX);
  Serial.print("  NR GSTAT 0x"); Serial.print(tmc_NR.GSTAT(), HEX);
  Serial.print("  NP GSTAT 0x"); Serial.println(tmc_NP.GSTAT(), HEX);

  // --- TMC2209 eye-pop drivers over shared UART ---
  tmcSerial.begin(115200, SERIAL_8N1, TMC2209_RX, TMC2209_TX);
  configTmc2209(tmc_EYE0);
  configTmc2209(tmc_EYE1);

  // --- Step generators ---
  engine.init();

  stepper_NL = engine.stepperConnectToPin(STEP_PIN_NL);
  if (stepper_NL) {
    stepper_NL->setDirectionPin(DIR_PIN_NL);
    stepper_NL->setSpeedInHz(NECK_SPEED_HZ);
    stepper_NL->setAcceleration(NECK_ACCEL);
    stepper_NL->setCurrentPosition(neckTargetInv(NECK_CENTER));
  }
  stepper_NR = engine.stepperConnectToPin(STEP_PIN_NR);
  if (stepper_NR) {
    stepper_NR->setDirectionPin(DIR_PIN_NR);
    stepper_NR->setSpeedInHz(NECK_SPEED_HZ);
    stepper_NR->setAcceleration(NECK_ACCEL);
    stepper_NR->setCurrentPosition(neckTarget(NECK_CENTER));
  }
  stepper_NP = engine.stepperConnectToPin(STEP_PIN_NP);
  if (stepper_NP) {
    stepper_NP->setDirectionPin(DIR_PIN_NP);
    stepper_NP->setSpeedInHz(NECK_SPEED_HZ);
    stepper_NP->setAcceleration(NECK_ACCEL);
    stepper_NP->setCurrentPosition(neckTarget(NECK_CENTER));
  }
  stepper_EYE = engine.stepperConnectToPin(STEP_PIN_EYE);
  if (stepper_EYE) {
    stepper_EYE->setDirectionPin(DIR_PIN_EYE);
    stepper_EYE->setSpeedInHz(EYE_SPEED_HZ);
    stepper_EYE->setAcceleration(EYE_ACCEL);
    stepper_EYE->setCurrentPosition(0);   // eyes retracted at boot
  }

  if (!stepper_NL || !stepper_NR || !stepper_NP || !stepper_EYE) {
    Serial.println("WARNING: a stepperConnectToPin() failed -- check STEP pins");
  } else {
    Serial.println("j4_stepper ready -- 5 motors connected, waiting for packets");
  }
}


void loop() {
  // Drain the link and parse complete newline-terminated lines.
  while (linkSerial.available()) {
    char c = (char)linkSerial.read();
    if (c == '\n') {
      rxBuf[rxLen] = '\0';
      if (rxLen > 0) parseLine(rxBuf);
      rxLen = 0;
    } else if (c == '\r') {
      // ignore
    } else if (rxLen < sizeof(rxBuf) - 1) {
      rxBuf[rxLen++] = c;
    } else {
      rxLen = 0;  // overflow -- drop the garbage line and resync on next '\n'
    }
  }
}
